#!/usr/bin/env bash
#
# SYNOPSIS
#     Раскрытие токенов в путях и строках конфигурации.
#
# DESCRIPTION
#     Поддерживаются две формы: ${ПЕРЕМЕННАЯ} - значение из окружения, и ~ в начале
#     пути - домашний каталог целевого пользователя.
#
#     Раскрытие намеренно НЕ использует eval: значение подставляется буквально, поэтому
#     содержимое конфигурации не может исполнить произвольный код. Это принципиально,
#     потому что config.json часто хранят в репозитории и правят всей командой.
#
#     Неизвестная переменная раскрывается в пустую строку, а не оставляет токен как есть:
#     оставленный ${FOO} в пути привёл бы к созданию файла с таким именем, что труднее
#     заметить, чем понятная ошибка на этапе валидации.

path_expand_tokens() {
    local input="${1:-}"
    local result=''
    local rest="$input"

    # ~ и ~/... - только в начале строки. Литерал вынесен в переменную, чтобы не
    # экранировать тильду внутри ${rest#...}: такое экранирование читается
    # неоднозначно и провоцирует ложные срабатывания линтера.
    local tilde_slash='~/'
    if [[ "$rest" == '~' ]]; then
        rest="${HOME:-/root}"
    elif [[ "$rest" == "$tilde_slash"* ]]; then
        rest="${HOME:-/root}/${rest#"$tilde_slash"}"
    fi

    # Кавычки одинарные намеренно: ищем ЛИТЕРАЛ "${", а не раскрытие переменной.
    # shellcheck disable=SC2016
    while [[ "$rest" == *'${'*'}'* ]]; do
        local before="${rest%%\$\{*}"
        local after="${rest#*\$\{}"
        local name="${after%%\}*}"
        rest="${after#*\}}"

        if [[ -n "$name" ]]; then
            result+="${before}${!name:-}"
        else
            result+="${before}\${}"
        fi
    done

    printf '%s%s' "$result" "$rest"
}

# Приводит путь к абсолютному (без обращения к файловой системе, чтобы работать
# и с ещё не существующими путями).
path_absolute() {
    local path="$1"
    if [[ "$path" == /* ]]; then
        printf '%s' "$path"
    else
        printf '%s/%s' "$(pwd)" "$path"
    fi
}
